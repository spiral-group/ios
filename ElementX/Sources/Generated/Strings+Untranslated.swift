// MARK: - Implementation Details

// AGENT-PLATFORM: the fork ships its own translations of the Untranslated
// table (there is no Localazy round-trip for a fork), so resolve through the
// user's preferred languages exactly like L10n.tr, falling back to en for
// keys a locale doesn't carry. `nonisolated` keeps parity with upstream's
// Swift 6.2 default-MainActor isolation change.
nonisolated extension UntranslatedL10n {
  static func tr(_ table: String, _ key: String, _ args: CVarArg...) -> String {
    // AGENT-PLATFORM (Brief 0083, question 359): the timeline's rows ask for their labels each time they're drawn.
    guard args.isEmpty else { return lookUp(table, key, args) }
    return Bundle.cachedTranslation(table: table, key: key) { lookUp(table, key, args) }
  }

  private static func lookUp(_ table: String, _ key: String, _ args: [CVarArg]) -> String {
    // Use preferredLocalizations to get a language that is in the bundle and the user's preferred list of languages.
    let languages = Bundle.overrideLocalizations ?? Bundle.app.preferredLocalizations

    for language in languages {
      if let translation = trIn(language, table, key, args) {
        return translation
      }
    }
    return trIn("en", table, key, args) ?? key
  }

  private static func trIn(_ language: String, _ table: String, _ key: String, _ args: [CVarArg]) -> String? {
    guard let bundle = Bundle.lprojBundle(for: language) else { return nil }
    let format = NSLocalizedString(key, tableName: table, bundle: bundle, comment: "")
    let translation = String(format: format, locale: Locale(identifier: language), arguments: args)
    guard translation != key,
          translation != "\(key) \(key)" // Handle double pseudo for tests
      else {
        return nil
      }
    return translation
  }
}

