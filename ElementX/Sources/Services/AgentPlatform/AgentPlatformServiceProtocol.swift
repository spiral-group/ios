/// Wire-mapped error taxonomy for the Agent Platform service
/// layer. Maps RFC 7807 problem details + transport errors into
/// the categories the UI cares about.
///
/// Mirrors `agent-platform-services.md` § Error handling. New
/// categories land here as the service surface widens
/// (rate-limit hint, session-mode-conflict, etc.).
nonisolated enum AgentPlatformError: Error, CustomStringConvertible {
    /// 401 — likely token rotated; trigger MAS re-login.
    case unauthorized
    /// 403 — caller is not the owner / wrong tenant.
    case forbidden
    /// 404 — resource doesn't exist (or caller cannot see it).
    case notFound
    /// 409 — state conflict (already decided, race, rate limit).
    case conflict(detail: String)
    /// 409 `/errors/target-blocked` on decide — an approve or edit of a
    /// cold-outreach card to someone the owner blocked. The platform closed
    /// the card (`expired`) instead and sent nothing.
    ///
    /// Not a `.conflict`: on decide that means "already decided", which the
    /// lock-screen runner takes as the decision having landed. Here the
    /// owner's approve did not happen, and they must hear so.
    case targetBlocked
    /// 404 `/errors/approval-not-found` on an approval's fetch or decide: the
    /// card is gone (its person was erased, so it was deleted and nothing was
    /// sent). Final, unlike a bare `.notFound`, which the platform also
    /// answers for a route it does not serve: a retry can outlive that.
    case approvalNotFound
    /// 409 `/errors/agent-paused` on an approve or edit: the owner paused the
    /// agent (decision 194). Nothing was decided; the card stays pending and
    /// can be approved after the resume. Not a `.conflict`, which the
    /// lock-screen runner takes as the decision having landed.
    case agentPaused
    /// 400 — malformed request body / params.
    case validation(detail: String)
    /// 5xx — server side problem.
    case serverError(status: Int)
    /// Transport / DNS / TLS / decode error.
    case transport(underlying: Error)

    /// The `type` URI the platform stamps on the blocked-target refusal.
    static let targetBlockedTypeURI = "/errors/target-blocked"
    /// The `type` URI the platform stamps on a missing approval.
    static let approvalNotFoundTypeURI = "/errors/approval-not-found"
    /// The `type` URI the platform stamps on a refusal because the agent is paused.
    static let agentPausedTypeURI = "/errors/agent-paused"

    var description: String {
        switch self {
        case .unauthorized: return "unauthorized — token may have rotated"
        case .forbidden: return "forbidden — owner / tenant mismatch"
        case .notFound: return "not found"
        case .conflict(let d): return "conflict: \(d)"
        case .targetBlocked: return "target blocked — the card is closed, nothing was sent"
        case .approvalNotFound: return "approval not found — the card is gone, nothing was sent"
        case .agentPaused: return "agent paused — nothing was decided, the card stays pending"
        case .validation(let d): return "validation failed: \(d)"
        case .serverError(let s): return "server error \(s)"
        case .transport(let e): return "transport: \(e.localizedDescription)"
        }
    }
}

