/// Slim shape consumed by the Settings screen. Wrapping the
/// generated `Operations.ListMyPersonalAgents.Output` keeps the
/// generated codegen module out of the rest of the app.
nonisolated struct MyPersonalAgentsView: Equatable {
    let agents: [PersonalAgentSummary]
    let provisioningStatus: ProvisioningStatus

    enum ProvisioningStatus: String, Equatable {
        case idle, inProgress = "in_progress", ready
    }
}

nonisolated struct PersonalAgentSummary: Equatable, Identifiable {
    let id: String
    let matrixUserID: String
    /// The agent's REAL name, as its owner configured it. Carried because the
    /// alternative is deriving a name from the MXID localpart — which is a
    /// login rendered as a name (`@assistant-emmm:…` → "Assistant Emmm") and
    /// disagrees with the name the same agent shows once it is in a room.
    let displayName: String
    /// The agent's avatar, when it has one. `nil` is normal today: nothing
    /// sets an avatar at provisioning, so most agents fall back to a letter —
    /// which is correct ONLY when the letter is seeded from `displayName`.
    let avatarMXC: String?
    let visibility: String
    let lifecycleState: String
}

nonisolated struct ApprovalSummary: Equatable, Identifiable {
    let id: String
    let agentID: String
    let draftBody: String
    let targetRoomID: String
    let createdAt: Date
    /// The person the draft concerns (the visitor, the outreach target, the
    /// sender to block), when the approval names one. Tells pending cards apart.
    var counterpartMXID: String?
}

// MARK: - Notifications hub (Brief 0041, ADR-0054)

/// One page of the notifications hub. `needsAction` is always the
/// FULL pending set (both families, TTL-bounded); `activity`
/// is the requested page of the terminal-outcome chronology.
nonisolated struct NotificationsSnapshot: Equatable {
    let needsAction: [NeedsActionItem]
    let activity: [AgentActivityEntry]
    /// Non-nil iff the activity page filled exactly `limit` rows.
    let nextActivityCursor: String?
    /// The owner's last-seen marker; `nil` when the hub was never
    /// opened (treat everything as unseen).
    let lastSeenAt: Date?
    /// Server-computed count of items in this response newer than
    /// `lastSeenAt`. Drives the bell badge.
    let unseenCount: Int
    /// What the owner's assistants kept about people they don't answer
    /// (decisions 194-196), newest first; the whole list on every page.
    var visitorMessages: [VisitorMessage] = []
}

/// An entry a personal assistant kept for its owner about someone it does
/// not answer: what they wrote, or a call it did not take.
nonisolated struct VisitorMessage: Equatable, Identifiable {
    enum Kind: Equatable {
        case message
        case missedCall
        /// A kind newer than this build: shown as a generic entry (decision 96).
        case other(String)

        init(serverValue: String) {
            switch serverValue {
            case "message": self = .message
            case "missed_call": self = .missedCall
            default: self = .other(serverValue)
            }
        }
    }

    let id: String
    let kind: Kind
    /// The assistant it was written to.
    let agentID: String
    let visitorMXID: String
    /// The one-to-one chat it was written in.
    let roomID: String
    /// What they wrote, as written; empty for a missed call.
    let body: String
    let createdAt: Date
}

/// Union row for the pinned "Needs action" section. Each family
/// keeps its existing summary type so detail routing reuses the
/// screens that already exist (ApprovalDetail handles approvals;
/// VerificationDetail handles verifications).
nonisolated enum NeedsActionItem: Equatable, Identifiable {
    case approval(ApprovalSummary)
    case verification(VerificationSummary)

    /// Family-prefixed so ids never collide across families in one
    /// SwiftUI `ForEach`.
    var id: String {
        switch self {
        case .approval(let approval): "approval-\(approval.id)"
        case .verification(let verification): "verification-\(verification.id)"
        }
    }

    /// Shared sort key — the hub interleaves the two families
    /// newest-first inside the pinned section.
    var createdAt: Date {
        switch self {
        case .approval(let approval): approval.createdAt
        case .verification(let verification): verification.createdAt
        }
    }
}

/// Full approval shape consumed by `ApprovalDetailScreen`. Mirrors
/// the backend's `ApprovalResponse` but with the `contextSnapshot`
/// parsed into our domain enum so the view doesn't poke at a
/// `[String: Any]` dictionary. The enum is exhaustive across the
/// backend "kinds" (`undefined` / `personal_agent_first_contact`
/// / `cold_outreach` / `block_sender`); a newer backend kind would
/// surface as `.unknown(rawKind:)` so the screen degrades gracefully
/// rather than crashing.
nonisolated struct ApprovalDetail: Equatable, Identifiable {
    let id: String
    let agentID: String
    /// Owner MXID. Logged for diagnostics; PII-safe per AGENTS.md
    /// (Matrix IDs are not secrets).
    let ownerUserID: String
    /// Draft body the agent proposes to send. The owner can
    /// override via `decision = .edit(newBody:)`.
    let draftBody: String
    /// Target Matrix room. Rendered in the detail header so the
    /// owner knows where the message will land.
    let targetRoomID: String
    let state: ApprovalState
    let context: ApprovalContext
    let createdAt: Date
    let updatedAt: Date
    /// `nil` until the orchestrator schedules expiry (typically
    /// 24 h after draft, 7 days for cold-outreach).
    let expiresAt: Date?
    /// Set once `state` leaves `pending`.
    let decidedAt: Date?
    let decidedBy: String?
    /// `escalation_reason` from the backend — set when the
    /// agent had to route through approval rather than auto-
    /// sending. Surfaced in the generic-card layout to give
    /// the owner context.
    let escalationReason: String?
}

extension ApprovalDetail {
