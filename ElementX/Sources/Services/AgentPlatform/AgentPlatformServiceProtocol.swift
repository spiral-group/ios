// MARK: - Verifications

/// Domain-side state machine for a verification approval. Mirrors
/// the backend's `VerificationApprovalState` (`pending_dh_exchange`
/// → `pending_owner` → `awaiting_remote_done` → `confirmed` /
/// `cancelled`). Stored as a string on the wire; we parse to this
/// enum at the service boundary so the UI doesn't pattern-match
/// on `String`.
nonisolated enum AgentVerificationState: Equatable {
    /// DH key exchange still in flight — emojis aren't available
    /// yet. The list keeps the row visible (so the owner sees
    /// "verification incoming") but the detail screen renders a
    /// "waiting for emojis" placeholder.
    case pendingDhExchange
    /// SAS key phase reached, emojis available, owner must
    /// decide. The detail screen renders the 7-emoji grid +
    /// strict-SAS checkbox + Confirm/Reject buttons.
    case pendingOwner
    /// Owner confirmed; the request is now waiting for the
    /// remote party's `m.key.verification.done` event. List
    /// hides this state by default (backend's
    /// `list_pending_for_agent` filters non-terminal only — so
    /// this state is fleeting but legitimate).
    case awaitingRemoteDone
    /// Terminal: both parties signed and the cross-signing keys
    /// are now trusted. Listed only on detail open if the
    /// flow finished during the screen's lifetime.
    case confirmed
    /// Terminal: someone cancelled (owner rejected, remote
    /// dropped, deadline elapsed, MAC mismatched, …). The wire
    /// `cancel_code` is preserved in `VerificationDetail` for
    /// diagnostics.
    case cancelled
    /// Forward-compat: a future backend introduced a new state.
    /// The UI degrades gracefully to "no actions available".
    case unknown(rawValue: String)

    var isActionable: Bool {
        if case .pendingOwner = self { return true }
        return false
    }
}

/// One SAS emoji + its description, mapped from the backend's
/// `EmojiResponse { glyph, description }`. The field name `symbol`
/// (not `glyph`) is deliberate: it matches upstream Element X's
/// `SessionVerificationEmoji` shape so the view layer can reuse
/// the same `EmojiView` rendering recipe and the same SASL10n
/// localised-description lookup. The service-layer mapper
/// translates wire `glyph` → DTO `symbol`.
///
/// The order of elements in `VerificationDetail.emojis` is
/// significant — both sides of the SAS exchange must agree on
/// the same ordered list, in the same order, or the MAC check
/// rejects.
nonisolated struct VerificationEmoji: Equatable, Hashable {
    /// Single emoji character (e.g. `🐶`). Named `symbol` to
    /// match upstream `SessionVerificationEmoji.symbol`.
    let symbol: String
    /// Human-readable label (e.g. `"Dog"`). Run through
    /// `SASL10n.localizedDescription(for:)` at render time so
    /// the user sees the localised label, not the wire's
    /// English-only string.
    let description: String
}

