// sourcery: AutoMockable
/// Owner-scoped service for the Agent Platform REST API
/// (`/api/v1/*` on spiral.md). Mirrors the Element X service-
/// layer pattern (e.g. `NotificationManagerProtocol`,
/// `SecureBackupControllerProtocol`).
///
/// M2.3 surface (S146 first cut): just enough to prove the
/// integration end-to-end + give the first UI screens
/// something to read. Further routes land additively as their
/// consuming UI ships; the underlying generated client
/// (`AgentPlatformClient.underlying`) already covers the full
/// /api/v1/* surface.
///
/// The `// sourcery: AutoMockable` annotation above generates
/// `AgentPlatformServiceMock` in `ElementX/Sources/Mocks/Generated/`
/// so ViewModels can inject a stub during unit / preview tests.
@MainActor
protocol AgentPlatformServiceProtocol: RoomToolsServiceProtocol {
    // `listMyPersonalAgents` and the room-scoped Tool + Trigger control
    // routes are inherited from `RoomToolsServiceProtocol` — the narrow
    // surface the in-room agent-tools flow depends on.

    // MARK: - Approvals

    /// `GET /api/v1/me/notifications` (Brief 0041 D3, ADR-0054).
    /// The notifications hub payload: needs-action union (pending
    /// approvals + verifications) + a cursor-
    /// addressed activity page + the last-seen marker + unseen
    /// count. `activityCursor == nil` fetches the first page.
    func fetchNotifications(activityCursor: String?,
                            limit: Int) async -> Result<NotificationsSnapshot, AgentPlatformError>

    /// `DELETE /api/v1/me/notifications/visitor-messages/{id}` (decision 195):
    /// the owner dismisses one kept entry; it is deleted for good. An entry
    /// already gone is `.notFound`.
    func dismissVisitorMessage(id: String) async -> Result<Void, AgentPlatformError>

    /// `POST /api/v1/me/push-devices` (Brief 0043, ADR-0057).
    /// Registers this device in the Spiral push registry — the
    /// fan-out set for the orchestrator's OWN push channel (no
    /// Matrix carrier event). Called next to the Synapse pusher
    /// registration; best-effort.
    func registerPushDevice(pushkey: String, appID: String) async -> Result<Void, AgentPlatformError>

    /// `PUT /api/v1/me/notifications/last-seen` (Brief 0041 D1b).
    /// Bumps the owner's marker to "now" (server clock). Returns
    /// the effective marker after the monotonic upsert.
    func markNotificationsSeen() async -> Result<Date, AgentPlatformError>

    /// `GET /api/v1/approvals/:id`. Drives the detail screen.
    /// Returns the full approval shape including the free-form
    /// `contextSnapshot` JSON which the UI reads to decide which
    /// of the three card layouts (generic / first-contact /
    /// cold-outreach) to render.
    func fetchApproval(id: String) async -> Result<ApprovalDetail, AgentPlatformError>

    /// `POST /api/v1/approvals/:id/decide`. Apply an approve /
    /// reject / edit decision. Returns the post-image of the
    /// approval plus a `DeliveryOutcome` describing whether the
    /// final Matrix message landed, didn't, or failed mid-send
    /// (in which case the UI surfaces a retry CTA).
    func decideApproval(id: String, decision: ApprovalDecision) async -> Result<ApprovalDecisionResult, AgentPlatformError>

    // MARK: - Cross-signing verifications (S156)

    /// `GET /api/v1/agents/:agent_id/verifications`. Returns the
    /// non-terminal verification approvals where the owner must
    /// compare SAS emojis with the requester out-of-band and
    /// decide. Lifecycle is owner-driven; the orchestrator only
    /// produces the row, it never confirms on the user's behalf.
    func listVerificationsForAgent(agentID: String) async -> Result<[VerificationSummary], AgentPlatformError>

    /// `GET /api/v1/verifications/:id`. Returns the full
    /// verification approval including the 7 SAS emojis if the
    /// flow has reached the `pending_owner` state. Before that
    /// (`pending_dh_exchange`) the `emojis` field is nil and
    /// the UI surfaces a "waiting for emojis" copy.
    func fetchVerification(id: String) async -> Result<VerificationDetail, AgentPlatformError>

    /// `POST /api/v1/verifications/:id/confirm` with body
    /// `{"comparison_acknowledged": true}`. Implementing types
    /// MUST always send `comparison_acknowledged: true` — the UI
    /// gates the call behind a strict-SAS checkbox so by the
    /// time the action fires the owner has already
    /// acknowledged. Returns the updated row (state moves to
    /// `awaiting_remote_done`).
    func confirmVerification(id: String) async -> Result<VerificationDetail, AgentPlatformError>

    /// `POST /api/v1/verifications/:id/reject`. Empty body. The
    /// owner explicitly declines (or the SAS emojis didn't
    /// match). Returns the updated row (state moves to
    /// `cancelled`).
    func rejectVerification(id: String) async -> Result<VerificationDetail, AgentPlatformError>

    // MARK: - Agent activity (Phase R3.5 E1)

    /// `GET /api/v1/agents/:agent_id/activity`. Owner-visible
    /// audit timeline backing the Agent Activity screen. Returns
    /// `agent_action_log` rows newest-first with cursor pagination
    /// + optional outcome filter.
    ///
    /// - Parameters:
    ///   - agentID: target agent. Caller MUST own this agent or
    ///     the backend returns 403.
    ///   - filter: outcome filter; `.all` (default) returns every
    ///     terminal + pending row.
    ///   - cursor: opaque continuation token from a previous
    ///     response's `nextCursor`. `nil` for the first page.
    ///   - limit: max rows per page. Clamped server-side to
    ///     `[1, 100]`. Default `25` matches `ApprovalsPage`.
    ///
    /// Wire shape pinned in
    /// `Brief 0002 § API contract / AgentActivityEntry`.
    func listAgentActivity(agentID: String,
                           filter: ActionOutcomeFilter,
                           cursor: String?,
                           limit: Int) async -> Result<AgentActivityPage, AgentPlatformError>

    // MARK: - Outreach queue (S159)

    /// `POST /api/v1/agents/:id/outreach-queue`. Enqueue a batch
    /// of target MXIDs. Backend hard-caps at 200 items per call;
    /// iOS clamps client-side to spare the round-trip on obvious
    /// overruns.
    ///
    /// Returns per-item outcomes (queued / duplicate / invalid)
    /// so the editor can render a result table — the user
    /// sees exactly which lines landed, which were ignored as
    /// dupes, and which failed validation with a reason.
    ///
    /// - Parameter agentID: outreach-kind agent id.
    /// - Parameter mxids: free-form list (one per line in the
    ///   editor UI). Empty array surfaces as `.validation` so
    ///   the editor's Save button stays disabled until the
    ///   buffer has at least one MXID.
    func enqueueOutreachTargets(agentID: String,
                                mxids: [String]) async -> Result<EnqueueOutreachResult, AgentPlatformError>

    /// `GET /api/v1/agents/:id/outreach-queue[?status=…]`.
    /// Returns queue rows newest-first. `status` is the wire
    /// DB-tag form (`queued` / `pending_approval` / `sent` /
    /// `blocked_by_target` / `content_blocked` / `error`).
    /// `nil` returns every row regardless of status.
    func listOutreachQueue(agentID: String,
                           status: OutreachTargetStatus?,
                           limit: Int) async -> Result<[OutreachQueueEntry], AgentPlatformError>

    // MARK: - Companies (S158)

    // MARK: - Public user profile (S157)

    /// `GET /api/v1/users/:mxid/profile`. Returns the user's
    /// MXID + derived display name + their publicly-contactable
    /// personal agents (filtered server-side to
    /// `visibility = public` + `lifecycle_state = active`).
    ///
    /// Any authenticated caller can read any user's profile —
    /// users opt out by toggling their agents private via the
    /// existing `PATCH /agents/:id/visibility` endpoint. The
    /// backend returns 404 when the user has no Matrix identity
    /// on the platform; 200 with `public_agents: []` for a user
    /// who exists but has hidden every agent.
    ///
    /// - Parameter mxid: target user MXID (e.g.
    ///   `@alice:spiral.md`). The caller is responsible for
    ///   ensuring this is a syntactically-valid MXID; the
    ///   backend returns 404 / 400 for malformed inputs.
    ///
    /// Wire shape pinned in
    /// `Brief 0001 § iOS scope / S157 PublicProfileScreen`.
    func fetchUserProfile(mxid: String) async -> Result<UserProfileView, AgentPlatformError>
    
    // MARK: - Invite links (Brief 0073 / ADR-0008)
    
    /// The caller's personal invite link (`GET /api/v1/me/invite`);
    /// the backend creates it on first call.
    func fetchMyInvite() async -> Result<MyInvite, AgentPlatformError>
    /// Who registered through the caller's links, newest first
    /// (`GET /api/v1/me/invite/joined`).
    func fetchMyInviteJoined() async -> Result<[InviteJoinedEntry], AgentPlatformError>
    
    // MARK: - New phrase from a signed-in device (Brief 0075)
    
    /// A one-time identity-page link that replaces the account phrase
    /// without the old one (`POST /api/v1/me/phrase-reset`). The caller
    /// asks for Face ID / the passcode first.
    func createPhraseReset() async -> Result<URL, AgentPlatformError>
    
    // MARK: - Account deletion (Brief 0078)
    
    /// Deletes the account everywhere (`DELETE /api/v1/me`): the person is
    /// erased in MAS, the assistant deactivated, the identity and bridge
    /// logins removed. `.notFound` means it is already gone; a 503 (MAS
    /// could not erase, nothing deleted) arrives as `.serverError(503)`.
    func deleteAccount() async -> Result<Void, AgentPlatformError>
    
    // MARK: - AI consent (Brief 0078 phase 2)
    
    /// The caller's consent to their data reaching third-party AI
    /// (`GET /api/v1/me/ai-consent`). The server is the source of truth.
    func fetchAIConsent() async -> Result<AIConsent, AgentPlatformError>
    /// Records the caller's decision for the disclosure in force
    /// (`PUT /api/v1/me/ai-consent`); `false` declines or withdraws.
    func setAIConsent(granted: Bool) async -> Result<AIConsent, AgentPlatformError>

    // MARK: - Your data (Brief 0078, GDPR)

    /// The caller's account export (`GET /api/v1/me/export`, GDPR Article 20),
    /// as the JSON the server sends.
    func exportAccountData() async -> Result<Data, AgentPlatformError>
    /// One page of the calls the caller's agents took part in, newest first
    /// (`GET /api/v1/voice-sessions`); pass the previous page's `nextCursor`.
    func listVoiceSessions(cursor: String?) async -> Result<VoiceSessionsPage, AgentPlatformError>
    /// One call's export (`GET /api/v1/voice-sessions/{id}/export`): its
    /// transcript, summary and consent log, as the JSON the server sends.
    func exportVoiceSession(sessionID: String) async -> Result<Data, AgentPlatformError>
    /// Erases one contact from every agent the caller owns
    /// (`DELETE /api/v1/me/memory`, ADR-0019 Principle 5) and returns what
    /// went — `.nothing` when there was nothing, also when the server says the
    /// caller has no account yet. Any other 404 is `.notFound`; the caller or
    /// their own agent as the contact is a `400` (`.validation`).
    func eraseAssistantMemory(aboutContact contactMXID: String) async -> Result<ContactErasure, AgentPlatformError>

    // MARK: - Agent blocks (decision 87)

    /// Which of the caller's agents block this person (`GET /api/v1/me/blocks`):
    /// agents that are not archived, one entry each, the earliest block. No
    /// blocks is an empty list; an MXID that does not canonicalise is a `400`
    /// (`.validation`).
    func listAgentBlocks(ofContact contactMXID: String) async -> Result<[AgentContactBlock], AgentPlatformError>
    /// One page of the people one agent blocks (`GET /api/v1/agents/{id}/blocks`,
    /// decision 194), newest first; `cursor` is the previous page's `nextCursor`.
    func listBlockedContacts(agentID: String, cursor: String?, limit: Int) async -> Result<AgentBlockedContactsPage, AgentPlatformError>
    /// The agent stops blocking the person (`DELETE /api/v1/agents/{id}/blocks`):
    /// they are a new contact again. Idempotent, so a stale read is safe: a
    /// person who is not blocked is a success too.
    func unblockContact(_ contactMXID: String, forAgent agentID: String) async -> Result<Void, AgentPlatformError>

    // MARK: - Owner blocks (decision 98)

    /// The owner's whole messenger ignore list, so that their agents ignore the
    /// same people (`PUT /api/v1/me/ignored-users`). Idempotent: the same list
    /// writes nothing, and the last write wins.
    func syncIgnoredUsers(_ userIDs: [String]) async -> Result<Void, AgentPlatformError>
    /// Fires when the platform dropped or created the rows the owner's blocks
    /// live in (an erase of an assistant's memory about a person, a new company
    /// agent, a new personal assistant), so the owner's ignore list must go
    /// again.
    var ownerBlocksResyncPublisher: AnyPublisher<Void, Never> { get }

    // MARK: - Public feed (AGENT-PLATFORM: feed, Brief 0082)

    /// The public feed's read side (lane I1).
    var feed: FeedServiceProtocol { get }

    /// The one change stream of the app (decision 289).
    var sync: PlatformSyncServiceProtocol { get }

    // MARK: - Unified Tool + Trigger control (Brief 0036 / ADR-0048)

    //
    // `fetchRoomTools` / `fetchToolsCatalog` / `armTool` / `disableTool`
    // are inherited from `RoomToolsServiceProtocol` (see that file). The
    // in-room agent-tools flow depends only on that narrow protocol.

    // MARK: - Agent-Spaces directory (Brief 0037)

    //
    // `listMyAgentSpaces` / `fetchAgentSpace` are inherited from
    // `RoomToolsServiceProtocol`: the add-agent picker lists every space's
    // agents (re-walk R1).

    /// `GET /api/v1/agents/{id}/read-model` — one agent's full detail
    /// (artboard 0037-D header + counters). Owner-gated.
    func fetchAgentReadModel(agentID: String) async -> Result<AgentReadModel, AgentPlatformError>

    /// `GET /api/v1/agents/{id}/usage` — the agent's AI use as shares of
    /// its daily limit (Brief 0079 3c). Owner-gated.
    func fetchAgentUsage(agentID: String) async -> Result<AgentUsage, AgentPlatformError>

    /// `GET /api/v1/agents/{id}/rooms` — agent-first room view: every
    /// room the agent lives in + its active tools there (0037-D
    /// LIVES-IN section). Owner-gated.
    func fetchAgentRooms(agentID: String) async -> Result<[AgentRoomEntry], AgentPlatformError>

    /// `POST /api/v1/agents/{id}/leave-room` — remove the agent from a
    /// room (artboard 0037-E destructive action). Server-side this is
    /// idempotent: Synapse "not in room" counts as success, and the
    /// agent's tools in that room are deactivated as cleanup.
    func leaveRoom(agentID: String, roomID: String) async -> Result<Void, AgentPlatformError>

    /// `POST /api/v1/agents/{id}/join-room` — the agent accepts the invite
    /// the owner sent into `roomID` (ADR-0017: an invite first, never a
    /// force-join), so it is in the chat when this returns.
    func joinRoom(agentID: String, roomID: String) async -> Result<Void, AgentPlatformError>

    /// `POST /api/v1/agent-spaces` — create a company space (artboard
    /// 0037-H). Returns the new space's summary so the flow can open
    /// it immediately. `brandingMXC` is the company logo the client
    /// uploaded itself via the Matrix SDK (Brief 0039: media is
    /// client-side) — it lands atomically with the space.
    func createCompany(name: String,
                       industry: String?,
                       website: String?,
                       brandingMXC: String?) async -> Result<AgentSpaceSummary, AgentPlatformError>

    /// `PATCH /api/v1/agent-spaces/{org_id}` — edit a company space's
    /// profile (Brief 0039 S4b). Only non-nil fields land in the patch;
    /// `brandingMXC` is a client-uploaded `mxc://` (empty string clears
    /// the logo).
    func updateCompanySpace(orgID: String,
                            name: String?,
                            industry: String?,
                            website: String?,
                            brandingMXC: String?) async -> Result<AgentSpaceSummary, AgentPlatformError>

    /// `POST /api/v1/agent-spaces/{org_id}/agents` — provision a role
    /// agent (sales / outreach / support) inside a company space (artboard
    /// 0037-F). The agent gets its own Matrix identity.
    func createCompanyAgent(companyID: String,
                            role: String,
                            displayName: String?,
                            roleBrief: String?) async -> Result<Void, AgentPlatformError>

    /// `GET /api/v1/agents/{id}/edit-schema` — the ADR-0049 published
    /// JSON Schema the edit form (artboard 0037-G) is rendered from.
    /// One schemars type on the backend = this schema + the server's
    /// bound validation, so the form can never drift from the API.
    func fetchAgentEditSchema(agentID: String) async -> Result<AgentEditSchema, AgentPlatformError>

    /// `PATCH /api/v1/agents/{id}` — THE agent write (Brief 0038): every
    /// changed field in one body. Not atomic: the profile is applied before
    /// the persona is checked, so a refusal can leave part of it saved.
    /// Answers the fresh read-model.
    func editAgent(agentID: String, patch: AgentEditPatch) async -> Result<AgentReadModel, AgentPlatformError>

    /// `DELETE /api/v1/agents/{id}` — archive the agent (artboard 0037-D
    /// '···' menu). Soft-archive: lifecycle flips, the Matrix user
    /// deactivates; the personal agent is re-provisioned by the
    /// reconciler with a new id, which the service then waits for
    /// (decision 136).
    func archiveAgent(agentID: String) async -> Result<Void, AgentPlatformError>

    // MARK: - In-call agent session controls (Brief 0054 / ADR-0071)

    /// `GET /api/v1/voice-sessions` filtered to the given room's
    /// live sessions. Backs the Element Call widget's
    /// `spiralBridge.getSessions()`.
    func voiceSessionControlContexts(roomID: String) async -> Result<[VoiceSessionControlContext], VoiceControlsError>

    /// `GET /api/v1/voice-sessions/{id}/controls`.
    func voiceSessionControls(sessionID: String) async -> Result<VoiceControlsState, VoiceControlsError>

    /// `GET /api/v1/voice/languages` (ADR-0094 A.8) — the voice-translation catalog, for anyone signed in.
    func voiceLanguages() async -> Result<[VoiceControlsCatalogLanguage], VoiceControlsError>

    /// `PUT /api/v1/voice-sessions/{id}/controls/translation`
    /// (`state: enabled`, ADR-0094 A.2). CAS-guarded by `revision`; 0 = no
    /// override row yet. A 503 is retried once after its `Retry-After`.
    func setVoiceTranslation(sessionID: String, params: VoiceTranslationParams, revision: Int32) async -> Result<VoiceControlsState, VoiceControlsError>

    /// `PUT /api/v1/voice-sessions/{id}/controls/translation`
    /// (`state: disabled`).
    func disableVoiceTranslation(sessionID: String, revision: Int32) async -> Result<VoiceControlsState, VoiceControlsError>

    /// `POST /api/v1/agents/{id}/voice-sessions` with attach-time
    /// controls (Brief 0055): add the agent to THIS call,
    /// session-scoped (`leave_policy=call_end`), configured
    /// explicitly. Returns the new session id (or the existing one on
    /// a benign 409). A 503 is retried once after its `Retry-After`.
    func attachVoiceAgent(agentID: String, roomID: String, params: VoiceAttachParams) async -> Result<String, VoiceControlsError>

    /// `DELETE /api/v1/voice-sessions/{id}` — remove the agent from
    /// the call (live teardown backend-side).
    func endVoiceSession(sessionID: String) async -> Result<Void, VoiceControlsError>

    /// `GET /api/v1/voice-sessions/{id}` — where an attached session is, and why it ended (question 387, B1).
    func voiceSessionProgress(sessionID: String) async -> Result<VoiceSessionProgress, VoiceControlsError>

    /// `GET /api/v1/agents/{id}/voice-sessions/join-check` — can the owner's agent join a call in this room
    /// (question 387, B4). A fact the backend could not read is `.unavailable`, not an answer.
    func voiceJoinCheck(agentID: String, roomID: String) async -> Result<VoiceJoinCheckReason, VoiceControlsError>

    /// `PUT …/controls/{control}` with `state=enabled|disabled` and no
    /// params — every on/off session control, CAS-guarded by `revision`.
    func setVoiceSwitch(sessionID: String, control: VoiceSessionSwitch, enabled: Bool, revision: Int32) async -> Result<VoiceControlsState, VoiceControlsError>
}

