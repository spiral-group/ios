/// One active tool inside an agent's room. Its words are the app's own,
/// built from the kind, the trigger and the audience: the server's
/// `params_summary` / `trigger_summary` are English and never shown.
nonisolated struct AgentRoomToolSummary: Equatable, Identifiable {
    let toolID: String
    let toolKind: String
    let targetLanguages: [String]
    /// When it fires; `nil` for a trigger this build doesn't know.
    var firing: AgentToolFiring?
    /// For whom; `nil` when the server didn't say.
    var audience: AudienceScope?

    var id: String {
        toolID
    }

    /// What the tool does.
    var localizedTitle: String {
        if toolKind == "translate" || toolKind == "live_translate", !targetLanguages.isEmpty {
            let names = targetLanguages.map { TranslationLanguageDisplayName.localizedName(for: $0) }
            return UntranslatedL10n.screenAgentToolsListTitleTranslate(names.joined(separator: ", "))
        }
        return ToolDisplayName.name(forKind: toolKind)
    }

    /// When it runs and for whom. `memberNames` names the people a
    /// `specific_senders` / `everyone_except` audience lists, by MXID.
    func localizedTrigger(memberNames: [String: String] = [:]) -> String? {
        AgentToolTrigger.line(firing: firing, audience: audience, memberNames: memberNames)
    }
}

