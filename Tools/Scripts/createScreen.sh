#!/bin/bash

GREEN='\033[0;32m'
NOCOLOR='\033[0m'

if [ ! $# -eq 1 ]; then
    echo -e "Usage: ${GREEN}./createScreen.sh Name${NOCOLOR}"
    echo -e "For example ${GREEN}./createScreen.sh Home${NOCOLOR} will create ${GREEN}HomeScreen${NOCOLOR}"
    exit 1
fi

SCREENS_DIR="../../ElementX/Sources/Screens"/$1Screen
UNIT_TESTS_DIR="../../UnitTests/Sources"

if [ -e $SCREENS_DIR ]; then
    echo "Error: Folder ${SCREENS_DIR} already exists"
    exit 1
fi

echo "Creating ${SCREENS_DIR}"

mkdir -p $SCREENS_DIR

echo "Copying screen files"

cp -R "Templates/SimpleScreenExample/ElementX/" $SCREENS_DIR/

echo "Copying tests"

cp -R "Templates/SimpleScreenExample/Tests/Unit/" $UNIT_TESTS_DIR/

SCREEN_NAME=$1
SCREEN_VAR_NAME=`echo $SCREEN_NAME | awk '{ print tolower(substr($0, 1, 1)) substr($0, 2) }'`

function rename_files {
    for file in $(find * -type f -print)
    do
      perl -p -i -e "s/Template/"$SCREEN_NAME"/g" $file
      perl -p -i -e "s/template/"$SCREEN_VAR_NAME"/g" $file

      mv ${file} ${file/Template/$SCREEN_NAME}
    done
}

# AGENT-PLATFORM: a screen made here is generated from Element's template, so
# its files keep the template's Element header and add the AGPL-3.0 §5(a)
# notice of modification (NOTICE, Tools/Scripts/element-derived-files.txt).
function restamp_headers {
    for file in $(find "$@" -type f -name '*.swift' -print)
    do
      perl -0 -p -i -e 's{\A(//\n(?:// Copyright [^\n]*\n)+)(//\n// SPDX-License-Identifier: )}{$1// Modified '"$(date +%Y)"' by the Spiral authors.\n$2}' "$file"
    done
}

restamp_headers $SCREENS_DIR $UNIT_TESTS_DIR/TemplateScreenViewModelTests.swift

echo "Renaming files"

cd $SCREENS_DIR
rename_files
cd - > /dev/null

cd $UNIT_TESTS_DIR
rename_files
cd - > /dev/null

# AGENT-PLATFORM: list the new files as made from Element's code, so
# preflight-archive.sh check [8] holds them to the header they carry.
function list_derived_files {
    local template generated
    for template in $(cd Templates/SimpleScreenExample && find ElementX Tests -type f -name '*.swift' -print | sort)
    do
      case "$template" in
        ElementX/*) generated="ElementX/Sources/Screens/${SCREEN_NAME}Screen/${template#ElementX/}" ;;
        Tests/Unit/*) generated="UnitTests/Sources/${template#Tests/Unit/}" ;;
      esac
      echo "${generated//Template/$SCREEN_NAME}  # Tools/Scripts/Templates/SimpleScreenExample/$template; generated by createScreen.sh from Element's template" >> element-derived-files.txt
    done
}

echo "Listing the files in element-derived-files.txt"

list_derived_files

echo "Done"
